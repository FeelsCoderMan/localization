package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	OUT_MESSAGE_FILE                  = "all_gen.go"
	OUT_MESSAGE_FILE_PERM os.FileMode = 0o444 // read-only for everyone
	PKG_MESSAGE                       = "message"
	STRUCT_NAME_MESSAGE               = "Message"
	FILE_EXT_GO                       = ".go"
	FILE_GO_TEST_SUFFIX               = "_test"
)

type item struct {
	name  string
	value string
	file  string
}

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	log.SetFlags(0)
	log.SetPrefix("genmessages: ")

	entries, err := os.ReadDir(".")
	if err != nil {
		return fmt.Errorf("could not read current directory with error: %w", err)
	}

	items := []item{}
	seen := make(map[string]item)

	fset := token.NewFileSet()
	for _, entry := range entries {
		fileName := entry.Name()

		if entry.IsDir() || strings.HasSuffix(fileName, FILE_GO_TEST_SUFFIX+FILE_EXT_GO) || fileName == OUT_MESSAGE_FILE {
			continue
		}

		astFile, err := parser.ParseFile(fset, fileName, nil, 0)
		if err != nil {
			return fmt.Errorf("could not parse the file of %s with error: %w", fileName, err)
		}

		for _, decl := range astFile.Decls {
			gd, ok := decl.(*ast.GenDecl)

			if !ok || gd.Tok != token.CONST {
				continue
			}

			for _, spec := range gd.Specs {
				vs := spec.(*ast.ValueSpec)
				id, ok := vs.Type.(*ast.Ident)

				if !ok || id.Name != STRUCT_NAME_MESSAGE {
					continue
				}

				for i, name := range vs.Names {
					if i >= len(vs.Values) {
						return fmt.Errorf("file %s: %s has no value", fileName, name.Name)
					}

					lit, ok := vs.Values[i].(*ast.BasicLit)
					if !ok || lit.Kind != token.STRING {
						return fmt.Errorf("file %s: %s must be a string literal", fileName, name.Name)
					}

					val, err := strconv.Unquote(lit.Value)
					if err != nil {
						return fmt.Errorf("file %s: %s could not be unquoted with error: %w", fileName, name.Name, err)
					}

					if prev, dup := seen[val]; dup {
						return fmt.Errorf("file %s: %s and %s (%s) share the value of %s", fileName, name.Name, prev.name, prev.file, val)
					}

					it := item{
						name:  name.Name,
						value: val,
						file:  fileName,
					}

					seen[val] = it
					items = append(items, it)
				}
			}
		}
	}

	if len(items) == 0 {
		return fmt.Errorf("no message constants found")
	}

	fmt.Printf("%d items are found\n", len(items))

	sort.Slice(items, func(i, j int) bool {
		return items[i].name < items[j].name
	})

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by genmessages: DO NOT MODIFY THE FILE\n")
	fmt.Fprintf(&buf, "package %s\n\n", PKG_MESSAGE)
	fmt.Fprintf(&buf, "// All lists every Message constant declared in this package\n")
	fmt.Fprintf(&buf, "var All = []Message{\n")

	for _, it := range items {
		fmt.Fprintf(&buf, "\t%s,\n", it.name)
	}

	fmt.Fprintf(&buf, "}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("could not source the buffer with error: %w", err)
	}

	if err := os.WriteFile(OUT_MESSAGE_FILE, out, OUT_MESSAGE_FILE_PERM); err != nil {
		return fmt.Errorf("could not write the buffer into file of %s with error: %w", OUT_MESSAGE_FILE, err)
	}

	return nil
}
